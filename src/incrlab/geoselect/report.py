"""Write reports/results/geoselect.json and reports/readouts/geoselect.md."""
from __future__ import annotations

from pathlib import Path
from typing import Optional

import numpy as np

from ..common.results import write_results
from ..config import REPORTS_DIR, REPO_ROOT
from .pipeline import GeoselectState


def _rel(p):
    try:
        return str(Path(p).resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(p)


def headline(S: GeoselectState) -> dict:
    t, c = S.pair["treatment"], S.pair["control"]
    return {
        "treatment_town": t["town"], "treatment_pop": t["pop"], "treatment_geoid": t["geoid"],
        "control_town": c["town"], "control_pop": c["pop"], "control_geoid": c["geoid"],
        "cluster": S.pair["cluster"], "cluster_size": S.pair["cluster_size"],
        "standardized_distance": S.pair["standardized_distance"],
        "n_geos_considered": int(len(S.geos)), "n_clusters": int(S.clustered["cluster"].nunique()),
        "sigma_gap": S.noise["sigma"], "rho": S.noise["rho"],
        "design_mde_at_test_weeks": S.mde, "test_weeks": S.st.test_weeks,
        "weeks_to_80pct_power_at_true_lift": S.weeks_to_power_at_true_lift,
        "true_lift": S.st.true_lift, "measured_lift": S.final["lift"],
        "ci_low": S.final.get("ci_low"), "ci_high": S.final.get("ci_high"),
        "ci_covers_truth": S.final.get("ci_covers_truth"), "verdict": S.verdict["label"],
    }


def build_estimates(S: GeoselectState) -> list:
    f = S.final
    return [{"test": "geoselect", "arm": "treatment_vs_matched_control", "metric": "conversions",
            "method": "change_ratio_did", "estimate": f["lift"], "ci_low": f.get("ci_low"),
            "ci_high": f.get("ci_high"), "ci_level": S.st.did_alpha and (1 - S.st.did_alpha),
            "p_value": None, "significant": bool(f.get("ci_low", -np.inf) > 0) if f.get("ci_low") is not None else None,
            "incremental": f.get("abs_effect"), "truth": S.st.true_lift,
            "notes": "weekly change-ratio DiD, full test window, week bootstrap CI"}]


def write_results_json(S: GeoselectState, results_dir: Optional[Path] = None):
    design = {"treatment": S.pair["treatment"], "control": S.pair["control"],
              "cluster": S.pair["cluster"], "feature_comparison": S.pair["feature_comparison"],
              "features_used": list(S.st.features), "kmeans_k": S.st.kmeans_k,
              "cluster_summary": S.cluster_summary.to_dict(orient="records")}
    validation = {"power": {"sigma_gap": S.noise["sigma"], "rho": S.noise["rho"],
                            "alpha_one_sided": S.st.alpha, "target_power": S.st.power_target,
                            "mde_at_test_weeks": S.mde, "test_weeks": S.st.test_weeks,
                            "power_curve": S.power_table.to_dict(orient="records"),
                            "weeks_to_80pct_power_at_true_lift": S.weeks_to_power_at_true_lift},
                 "monitoring_interim_looks": S.monitoring.to_dict(orient="records")}
    truth = {"true_lift": S.st.true_lift, "test_weeks": S.st.test_weeks, "test_days": S.st.test_days,
            "pre_period_days": S.st.pre_period_days, "daily_noise_sd": S.st.daily_noise_sd}
    census_doc_src = ("US Census ACS 2018-2022 5-Year Summary File (table-based, www2.census.gov, no "
                      "API key) + 2023 Census Gazetteer cousubs file; api.census.gov Data API requires "
                      "a key for data queries (302->missing_key.html) so the key-free bulk distribution "
                      "was used instead - same underlying ACS 5yr estimates, real MA geography.")
    extra = {"census_data_source": census_doc_src,
            "synthetic_assumptions": ("baseline_kpi_rate is a SYNTHETIC performance proxy correlated "
                                      "with real demographics (see census_data.synth_baseline_kpi); the "
                                      "test window outcomes (run_test.py) and monitoring are simulated "
                                      "daily conversions with a known injected true lift."),
            "verdict": S.verdict, "final_readout": S.final}
    return write_results("geoselect", headline(S), build_estimates(S), design=design, validation=validation,
                         truth=truth, figures=[_rel(f) for f in S.figures], extra=extra,
                         results_dir=results_dir)


def write_readout_md(S: GeoselectState, path: Optional[Path] = None) -> Path:
    h = headline(S)
    f = S.final
    v = S.verdict
    md = f"""# Geo-experiment selection & readout (Massachusetts, real Census demographics) — readout

*Geography and demographics are REAL (US Census ACS 2018-2022 5yr, MA county subdivisions). The
baseline performance KPI, the test-window outcomes and the monitoring data are SIMULATED (true lift
is known by construction). Generated by `python -m incrlab.geoselect`; every number below is in
`reports/results/geoselect.json`.*

**Verdict: {v['label'].upper()}.** Treatment market **{h['treatment_town']}** (pop {h['treatment_pop']:,.0f})
vs matched control **{h['control_town']}** (pop {h['control_pop']:,.0f}), both in cluster {h['cluster']}
(cluster size {h['cluster_size']}, standardized distance {h['standardized_distance']:.3f}). Measured
DiD lift **{f['lift']:+.1%}** [90% CI {f.get('ci_low', float('nan')):+.1%}, {f.get('ci_high', float('nan')):+.1%}]
vs true injected lift **{h['true_lift']:+.1%}** — the interval **{'covers' if f.get('ci_covers_truth') else 'misses'}** the truth.

## 1. Market clustering (real Census ACS demographics)
{h['n_geos_considered']} Massachusetts county subdivisions (towns/cities) with ACS 5yr population
>= {int(S.st.pop_threshold):,} were pulled from the Census Bureau's ACS 2018-2022 5-Year Summary File
(bulk, key-free distribution — see note below) and K-means clustered (k={S.st.kmeans_k}) on real median
household income, median age, % bachelor's+, % white, % Hispanic, log population density, log
population, plus a synthetic baseline-KPI feature (see §2). See `01_clusters.png`.

## 2. Matched-market selection + power analysis
Within the richest matched cluster, the two closest geos by standardized distance were chosen as
treatment/control. A synthetic weekly "conversions per 1,000 population" baseline (demographically
driven, NOT real business data — documented in `census_data.synth_baseline_kpi`) was used so matching
and power have a performance proxy beyond pure demographics.

Daily-noise-implied gap sd = **{h['sigma_gap']:.3f}**, AR(1) rho = **{h['rho']:.2f}**. Closed-form DiD
MDE at {h['test_weeks']} test weeks / {S.st.power_target:.0%} power = **{h['design_mde_at_test_weeks']:.1%}**;
weeks needed to reach {S.st.power_target:.0%} power at the true {h['true_lift']:.0%} lift =
**{h['weeks_to_80pct_power_at_true_lift'] or 'n/a'}**. See `02_power_ladder.png`.

## 3. Simulated test run + monitoring
A {S.st.test_days}-day ({h['test_weeks']}-week) test window was simulated for both markets, with the
true {h['true_lift']:+.0%} lift injected into the treatment market's daily conversions from day 1. A
weekly change-ratio DiD interim look was taken after each completed test week (sequential monitoring).
See `03_monitoring.png`.

## 4. Final readout
| Metric | Estimate | 90% CI | Truth | Covered |
|---|---|---|---|---|
| Conversions lift (change-ratio DiD) | {f['lift']:+.1%} | [{f.get('ci_low', float('nan')):+.1%}, {f.get('ci_high', float('nan')):+.1%}] | {h['true_lift']:+.1%} | {'yes' if f.get('ci_covers_truth') else 'no'} |

See `04_final_readout.png`.

## Census data source note
api.census.gov's tabular Data API now requires a registered key for every data query (metadata
queries are exempt); without one, every request 302-redirects to `missing_key.html`. We pulled
the same underlying ACS 2018-2022 5-year estimates from the Census Bureau's public, key-free bulk
distribution instead: the table-based Summary File (`www2.census.gov/.../table-based-SF/data/5YRData/`)
for B01003 (population), B19013 (median household income), B01002 (median age), B02001 (race),
B03002 (Hispanic/Latino ethnicity), B15003 (educational attainment), joined to the 2023 Census
Gazetteer county-subdivisions file for land area. No rate-limit or partial-data issue was encountered
with this bulk path; it is real public ACS data for real MA geographies, not synthetic geography.

## Honest caveats
- The baseline KPI and all test-window outcomes are simulated; only the geography, demographics and
  clustering are real Census data.
- A single simulated test window is a single noise draw; a different seed would move the point
  estimate within the stated interval.
- The matched pair is chosen purely on demographic + synthetic-KPI similarity; a real deployment
  would also check pre-period trend parallelism on the actual business KPI before launch.
"""
    p = Path(path or REPORTS_DIR / "readouts" / "geoselect.md")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(md)
    return p
